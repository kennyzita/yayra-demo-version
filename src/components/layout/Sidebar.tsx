const staffNav: NavItem[] = [
  { href: '/staff/dashboard', label: 'Dashboard', icon: <DashIcon /> },
  { href: '/staff/clients', label: 'My Clients', icon: <UsersIcon /> },
  { href: '/staff/timesheet', label: 'Timesheet', icon: <ClockIcon /> },
  { href: '/staff/case-notes', label: 'Case Notes', icon: <NoteIcon /> },
  { href: '/staff/documents', label: 'Documents', icon: <FolderIcon /> },
  { href: '/staff/training', label: 'Training', icon: <BookIcon /> },
]

export function Sidebar({ role, userName, userEmail }: SidebarProps) {
  const pathname = usePathname()
  const router = useRouter()
  const supabase = createClient()
  const navItems = role === 'admin' ? adminNav : staffNav

  const initials = userName
    .split(' ')
    .map((n) => n[0] ?? '')
    .join('')
    .toUpperCase()
    .slice(0, 2)

  async function handleSignOut() {
    await supabase.auth.signOut()
    router.push('/login')
    router.refresh()
  }

  return (
    <div className="flex flex-col h-full w-64 shrink-0 bg-[#002830] text-white">
      {/* Logo */}
      <div className="px-6 py-5 border-b border-white/10">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 rounded-lg bg-[#30B060] flex items-center justify-center shrink-0">
            <span className="text-white font-bold text-lg">Y</span>
          </div>
          <div>
            <h1 className="text-white font-bold text-lg leading-none">YayraCare</h1>
            <p className="text-white/40 text-xs mt-0.5">
              {role === 'admin' ? 'Admin Portal' : 'Staff Portal'}
            </p>
          </div>
        </div>
      </div>

      {/* Nav */}
      <nav className="flex-1 px-3 py-4 space-y-0.5 overflow-y-auto">
        {navItems.map((item) => {
          const isActive = pathname === item.href
          return (
            <Link
              key={item.href}
              href={item.href}
              className={cn(
                'flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors',
                isActive
                  ? 'bg-[#30B060] text-white'
                  : 'text-white/60 hover:text-white hover:bg-white/10'
              )}
            >
              <span className={cn('shrink-0', isActive ? 'text-white' : 'text-white/50')}>
                {item.icon}
              </span>
              {item.label}
            </Link>
          )
        })}
      </nav>

      {/* User + sign out */}
      <div className="px-3 py-4 border-t border-white/10">
        <div className="flex items-center gap-3 px-3 py-2 mb-1">
          <div className="w-8 h-8 rounded-full bg-[#008080] flex items-center justify-center shrink-0">
            <span className="text-white text-xs font-semibold">{initials}</span>
          </div>
          <div className="flex-1 min-w-0">
            <p className="text-white text-sm font-medium truncate">{userName}</p>
            <p className="text-white/40 text-xs truncate">{userEmail}</p>
          </div>
        </div>
        <button
          onClick={handleSignOut}
          className="w-full flex items-center gap-3 px-3 py-2 rounded-lg text-sm text-white/60 hover:text-white hover:bg-white/10 transition-colors"
        >
          <svg className="w-5 h-5 shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          Sign out
        </button>
      </div>
    </div>
  )
}
